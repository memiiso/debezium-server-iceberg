package io.debezium.server.iceberg.converter.geospatial;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HexFormat;
import java.util.List;
import java.util.stream.Stream;
import org.apache.iceberg.GeometryFieldMetrics;
import org.apache.iceberg.types.Types;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

/** Fixture generated by PostGIS: ST_AsEWKB (Debezium input) and ST_AsBinary (expected). */
class WkbConverterTest {

  private static final Path FIXTURE =
      Path.of("src/test/resources/geospatial/postgis-ewkb-iso-wkb.psv");
  // Iceberg 1.12 limit: no bounds for curves, PolyhedralSurface, TIN, Triangle
  private static final List<String> UNBOUNDED_TYPES =
      List.of("CIRCULARSTRING", "COMPOUNDCURVE", "CURVE", "SURFACE", "TIN", "TRIANGLE");

  static Stream<Arguments> postgisGeometries() throws IOException {
    return Files.readAllLines(FIXTURE).stream()
        .filter(line -> !line.isBlank() && !line.startsWith("#"))
        .map(line -> line.split("\\|"))
        .map(
            cols ->
                Arguments.of(
                    cols[0], HexFormat.of().parseHex(cols[1]), HexFormat.of().parseHex(cols[2])));
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("postgisGeometries")
  void testEwkbToIsoWkbMatchesPostgis(String geometry, byte[] ewkb, byte[] isoWkb) {
    assertArrayEquals(isoWkb, WkbConverter.toIsoWkb(ewkb), geometry);
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("postgisGeometries")
  void testIsoWkbIsUnchanged(String geometry, byte[] ewkb, byte[] isoWkb) {
    assertArrayEquals(isoWkb, WkbConverter.toIsoWkb(isoWkb), geometry);
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("postgisGeometries")
  void testIcebergComputesBounds(String geometry, byte[] ewkb, byte[] isoWkb) {
    if (geometry.contains("EMPTY") || UNBOUNDED_TYPES.stream().anyMatch(geometry::contains)) {
      return;
    }
    GeometryFieldMetrics.Builder metrics =
        new GeometryFieldMetrics.Builder(1, Types.GeometryType.crs84());
    metrics.addValue(ByteBuffer.wrap(WkbConverter.toIsoWkb(ewkb)));
    GeometryFieldMetrics result = metrics.build();
    assertNotNull(result.lowerBound(), geometry);
    assertNotNull(result.upperBound(), geometry);
  }

  @Test
  void testInvalidWkb() {
    for (String hex :
        List.of(
            "0101000020e6100000000000000000f03f", // EWKB point, truncated coordinates
            "0163000080", // unknown geometry type 99
            "0101000000000000000000f03f000000000000004000", // ISO point, trailing byte
            "0201000000000000000000f03f0000000000000040", // invalid byte order
            "0103000000ffffffff", // polygon, negative ring count
            "0104000000ffffffff", // multipoint, negative element count
            "0102000000ffffff7f", // linestring, point count overflows
            "0189130000000000000000f03f0000000000000040", // point, type 5001 (no dimension 5)
            "0101")) { // too short
      assertThrows(
          IllegalArgumentException.class,
          () -> WkbConverter.toIsoWkb(HexFormat.of().parseHex(hex)),
          hex);
    }
  }
}
